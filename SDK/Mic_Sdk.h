/* ============================================================
 * Mic_Sdk.h —— 下位机通讯 SDK 缩小版（自包含单文件 + 统一接口头）
 * ------------------------------------------------------------
 * 指令保留 0x01 转速 / 0x02 开放修改权 / 0x03 停止 / 0x04 方向（运行中
 *            拒改防瞬间反向，静止可改）/ 0x0B 查询 SetRpm，
 * 应答保留 0x80 ACK（固定 7 字节 = 指令码+结果+编号+值4B 大端，全指令统一格式）
 *   / 0x81 心跳反馈（停止 3 字节 = 联机位+报警+脚踏，运行中 8 字节 =
 *   联机位+转速(3)+电流(2)+报警+脚踏，报警态按 inf 位图累加 3~13 字节）
 *
 * 架构（中继站模式）：SDK 仅做指令/状态的中转透传，不承载业务逻辑——
 * 协议层收到指令 → 直接编辑 sdk 设置位 → sdk_exec 镜像到硬件 →
 * heart_feedback 读走上报；电机启停由下位机硬件自循环控制，上位机
 * 0x02 仅开放 SetRpm 修改权（SoftwareRun_flag=1），不启动电机
 *
 * 协议（简化版）：起始位(0x2F) + CMD + LEN + DATA（无 CRC，帧总长=LEN+3）
 *
 * 使用方式：
 *   1) 串口接收中断里每收 1 字节调一次 rx_handle_byte(b)；
 *   2) 主循环 while(1) 里每圈调一次 Mic_Sdk_Poll()；
 *   3) 在 Mic_Sdk.c 的 uart_send_byte() 里实现串口发送（唯一对接点）
 * ============================================================ */
#ifndef MIC_SDK_H
#define MIC_SDK_H

#include <stdint.h>

/* ============================================================
 * 应用状态结构体 —— 协议层与应用层的公共数据中心
 * 协议层（rx_resolve）：指令到达直接编辑对应设置位（启动位/停止位等）
 * 应用层：Mic_Sdk_Exec 仅镜像状态到硬件；
 *         实时值由下位机采集层直接写入（本模块不采集）
 * ============================================================ */
typedef struct _Sdk
{
    /* 标志位 */
    /* 联机握手位：上电默认 0；0x02 开放修改权置 1（上位机打开设置面板），
     * 0x03 DATA=1 断开清 0、固件复位回 0——电机启停由 MotorRun/MotorStop
     * 表达（实体脚踏自动控制） */
    uint8_t SoftwareRun_flag;//软件运行标志位 0:未握手 1:已握手(联机)
    /* 设置状态位（瞬时）：0x01 处理期间置 1（正在设置，拒绝重入）；
     * 下位机完成 置位→赋值 后、给上位机发送确认信息
     * （ACK+补发 0x81 长帧）之前清 0——发送时已置 0 表示设置流程
     * 结束、允许下一次修改；0x01 纯设置转速，不操作启停位
     * （电机启停由实体脚踏自动控制） */
    uint8_t SetRpm_flag;//设置转速标志位 0:空闲 1:正在设置(瞬时)

    /* 原机参数 */
    /* 启停位：脚踏/面板按键事件直接编辑（按下=启动，松开=无其他
     * 按键才停止，脚踏优先）；应用层 Exec 读此位驱动硬件 */
    uint8_t MotorRun;//启动位（1=运行中 0=未运行；按键按下置 1，与 MotorStop 互锁）
    uint8_t MotorStop;//停止位（1=停止态 0=非停止；按键松开置 1，与 MotorRun 互锁；上电默认 Run=0 Stop=1）
    /* 与转速设置同模式：上位机 0x04 指令触发写入（1=正转 2=反转），
     * 应用层读此位输出方向 IO */
    uint8_t MotorDir;//方向 1=正转 2=反转（运行中 MotorRun=1 拒改，静止可改）
    uint8_t MotorPower;//供电 0:断电 1:供电（缩小版无 0x06 写入指令，恒为上电默认 0；应用层可本地写）
    /* 按键信号（上位机 0x0A 或实体按键写入，0/1 电平对应）：
     * 上位机发按键信号(data[0]=类型 data[1]=0/1) → 写对应按键位；
     * 脚踏/面板按下(=1) → 级联 MotorRun=1 MotorStop=0，松开恢复；
     * 高低速按下沿 → 档位切换（SetRpm/SetElecricity 成对改写） */
    uint8_t TBAJ;//脚踏按键 0:松开 1:踩住（请求运行）
    uint8_t ZXAJ;//面板按键 0:松开 1:按住（请求运行，与脚踏同功能独立信号）
    uint8_t GDQHAJ;//高低速按键 0:未按下 1:按下（触发档位切换）

    /* 本地参数 */
    /* 上位机 0x01 触发写入（SetRpm_flag 同步置 1），≤99999 */
    uint32_t SetRpm;//设置转速参数（上位机传输的设置值）
    uint32_t Rpm;//转速参数（应用层实时采集，心跳上报）
    /* 上位机是否可修改待定：当前应用层本地设置
     * （高低速档位切换时成对改写），协议暂无电流指令 */
    uint16_t SetElecricity;//设置电流参数（mA）
    uint16_t Electricity;//电流（应用层实时采集，心跳上报）
    /* ERR 三态（下位机第一优先状态，运行帧 d[6]/短心跳 d[1]）：
     *   0=正常  1=过载  2=故障
     * 纯应用层数据源（协议层不写）：采集检测写入——
     * 电流超限写 1=过载，过温/堵转等写 2=故障，恢复正常写 0；
     * 指令执行与否由旗帜位本身表达（ACK 结果=旗帜位镜像）
     * 处置归属：ERR≠0 时下位机不改变电机行为（本体保护由
     * 硬件电流限制承担），仅上报错误码供上位机对照处置——
     * 上位机据此显示过载/故障态并禁止启动 */
    uint8_t ERR;//错误码 0=正常 1=过载 2=故障
}_Sdk;

/* 全局唯一实例（定义在 Mic_Sdk.c） */
extern _Sdk sdk;

/* ============================================================
 * 接收侧 API
 * ============================================================ */

/* 初始化（上电时调用一次） */
void rx_init(void);

/* 接收字节处理：串口接收中断里每收 1 字节调用一次（耗时 < 1us） */
void rx_handle_byte(uint8_t b);

/* 主循环消费处理：Mic_Sdk_Poll 内部自动调用，有数据即解析（不等攒满）——
 * 帧攒齐立即处理（指令下一圈即 ACK 应答）；未攒齐在途等待（不切帧）；
 * 假帧头卡死靠空闲计数（连续 N 圈无新字节）逐字节清障；
 * 返回值：恒 0（旗帜位已直接编辑并回 ACK 镜像，无累计计数） */
uint8_t rx_poll(void);

/* ============================================================
 * 应用层 API
 * ============================================================ */

/* 应用层主循环 —— while(1) 里每圈调用一次，内部依次完成：
 *   ① 指令解析（rx_poll → 指令直接编辑 sdk 设置位）
 *   ② 硬件输出（Mic_Sdk_Exec 镜像 sdk 状态 → 驱动硬件）
 *   ③ 心跳上报（heart_feedback 发 0x81 反馈帧）
 * 注：Rpm/Electricity/ERR/TBAJ 等实时数据由下位机采集层直接写入
 *     sdk（如定时器中断/ADC 采样/硬件自循环），本模块不负责采集；
 *     本 SDK 仅为中继站，电机启停等业务逻辑由下位机硬件自循环处理 */
void Mic_Sdk_Poll(void);

/* 心跳上报 —— 单发一帧 0x81 综合反馈（组帧+发送一体）
 * Mic_Sdk_Poll 内部每圈自动调用；也可用硬件定时器按固定间隔
 * 单独调用实现精确周期 */
void heart_feedback(void);

#endif /* MIC_SDK_H */
